#!/usr/bin/env node
// The deck-visuals skill's preset reference (feature 002, T142; research
// D5): `npm run presets:doc` writes references/presets.md from the preset
// registry (src/presets/registry.ts) and each preset's example file
// (src/presets/slides/, feature 003, T331) into both copies of the skill,
// .claude/skills/deck-visuals/ and .agents/skills/deck-visuals/. Each preset
// gets its name, family, block type, layout, the source structure it fits,
// its example file's path and the file itself. tests/tools/skill_test.mjs
// fails when the reference is out of date.
//
// Runs under plain Node: the registry imports types only.
//
// The module exports `presetsDoc` for the test; main() runs only when the
// file is invoked directly.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { families, registry } from "../src/presets/registry.ts";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The skill's two copies, relative to the repository root. */
export const SKILL_DIRS = [
  ".claude/skills/deck-visuals",
  ".agents/skills/deck-visuals",
];

/** The families' names, as contracts/presets.md gives them. */
const familyNames = {
  charts: "Charts and stats",
  diagrams: "Diagrams",
  text: "Text layouts",
  images: "Image slides",
};

/** A preset's example file, relative to the repository. */
const exampleFile = (entry) => `src/presets/slides/${entry.file}.tsx`;

/** The reference for a list of presets, as markdown, with the example
 *  files read from `root`. */
export function presetsDoc(entries = registry, root = repoRoot) {
  const out = [
    "# Presets",
    "",
    "Generated by `npm run presets:doc` (`scripts/presets-doc.mjs`) from the preset registry, `src/presets/registry.ts`, and each preset's example file in `src/presets/slides/`. Do not edit it by hand: change the registry or a file and run the script.",
    "",
    "Each preset is a slide file. To use one, copy its file into `src/slides/` with a number (`NN-name.tsx`), put the owner's words and figures in its `copy`, and change its JSX freely. Every word and figure a slide shows comes from `copy`, which has the same keys for each language in `src/deck/langs.ts`; never type one into the JSX (`scripts/check-inline-text.mjs` fails on it). The example files carry placeholder words and placeholder numbers only. Every preset is drawn in the gallery at `/gallery`, with its example and a second, different one (`src/presets/slides/alternates/`).",
    "",
  ];
  for (const family of families) {
    const members = entries.filter((entry) => entry.family === family);
    if (!members.length) continue;
    out.push(`## ${familyNames[family]}`, "");
    for (const entry of members) {
      out.push(
        `### ${entry.name}`,
        "",
        `- Family: \`${entry.family}\``,
        `- Block: \`${entry.block}\``,
        `- Layout: \`${entry.layout}\``,
        `- Fits: ${entry.fits}`,
        `- File: \`${exampleFile(entry)}\``,
        "",
        "```tsx",
        readFileSync(join(root, exampleFile(entry)), "utf8").trim(),
        "```",
        "",
      );
    }
  }
  return out.join("\n");
}

/** Writes the reference into both copies of the skill under `root`. */
export function writePresetsDoc(root = repoRoot) {
  const doc = presetsDoc();
  const written = [];
  for (const dir of SKILL_DIRS) {
    const path = join(root, dir, "references", "presets.md");
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, doc);
    written.push(join(dir, "references", "presets.md"));
  }
  return written;
}

function main() {
  for (const path of writePresetsDoc()) console.log(`wrote ${path}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
