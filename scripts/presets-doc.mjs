#!/usr/bin/env node
// The deck-visuals skill's preset reference (feature 002, T142; research
// D5): `npm run presets:doc` writes references/presets.md from the preset
// registry (src/presets/registry.ts) into both copies of the skill,
// .claude/skills/deck-visuals/ and .agents/skills/deck-visuals/. Each preset
// gets its name, family, block type, the source structure it fits, and its
// example as compact JSON. tests/tools/skill_test.mjs fails when the
// reference is out of date.
//
// Runs under plain Node: the registry imports types only.
//
// The module exports `presetsDoc` for the test; main() runs only when the
// file is invoked directly.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { families, registry } from "../src/presets/registry.ts";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The skill's two copies, relative to the repository root. */
export const SKILL_DIRS = [
  ".claude/skills/deck-visuals",
  ".agents/skills/deck-visuals",
];

/** The families' names, as contracts/presets.md gives them. */
const familyNames = {
  charts: "Charts and stats",
  diagrams: "Diagrams",
  text: "Text layouts",
  images: "Image slides",
};

/** The reference for a list of presets, as markdown. */
export function presetsDoc(entries = registry) {
  const out = [
    "# Presets",
    "",
    "Generated by `npm run presets:doc` (`scripts/presets-doc.mjs`) from the preset registry, `src/presets/registry.ts`. Do not edit it by hand: change the registry and run the script.",
    "",
    "Each preset is a block in a slide's `blocks`, in `src/deck/slides.ts`. Every `Text` has a string for each language in `src/deck/langs.ts`. The examples carry placeholder words and placeholder numbers only. The limits of each block are in `src/presets/validate.ts`. Every preset is drawn in the gallery at `/gallery`, with its example and a second, different one.",
    "",
  ];
  for (const family of families) {
    const members = entries.filter((entry) => entry.family === family);
    if (!members.length) continue;
    out.push(`## ${familyNames[family]}`, "");
    for (const entry of members) {
      out.push(
        `### ${entry.name}`,
        "",
        `- Family: \`${entry.family}\``,
        `- Block: \`${entry.block}\``,
        ...(entry.layout ? [`- Layout: \`${entry.layout}\``] : []),
        `- Fits: ${entry.fits}`,
        "",
        "```json",
        JSON.stringify(entry.example),
        "```",
        "",
      );
    }
  }
  return out.join("\n");
}

/** Writes the reference into both copies of the skill under `root`. */
export function writePresetsDoc(root = repoRoot) {
  const doc = presetsDoc();
  const written = [];
  for (const dir of SKILL_DIRS) {
    const path = join(root, dir, "references", "presets.md");
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, doc);
    written.push(join(dir, "references", "presets.md"));
  }
  return written;
}

function main() {
  for (const path of writePresetsDoc()) console.log(`wrote ${path}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
